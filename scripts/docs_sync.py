"""Keep translated docs in sync with the English originals.

Every English doc starts with ``<!-- doc-id: <id> | rev: <8 hex> -->`` where rev is the
hash of its content. A translation under ``languages/<lang>/`` starts with
``<!-- doc-id: <id> | lang: <lang> | source-rev: <rev> -->``. A translation is current
while its source-rev equals the English rev.

    python scripts/docs_sync.py bump                 # recompute English revs, rewrite STATUS.md
    python scripts/docs_sync.py check                # exit 1 if a rev or STATUS.md is out of date
    python scripts/docs_sync.py stamp vi [doc ...]   # (re)write ID line + banner, fix relative links
    python scripts/docs_sync.py status               # print STATUS.md

See languages/README.md and AGENTS.md for the workflow.
"""
from __future__ import annotations

import hashlib
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG_DIR = ROOT / "languages"
LANGS = {"vi": "Tiếng Việt", "zh": "中文", "ja": "日本語", "es": "Español"}
BANNERS = {
    "vi": "> 🌐 **Bản dịch tiếng Việt** của [`{src}`]({link}) (rev `{rev}`). Bản tiếng Anh là chuẩn: nếu hai bản khác nhau, hãy theo bản tiếng Anh. Bản dịch do máy thực hiện, chưa có người bản xứ rà soát.",
    "zh": "> 🌐 **中文翻译**，源文件 [`{src}`]({link})（rev `{rev}`）。以英文版为准：若两者不一致，请以英文版为准。本译文由机器翻译，尚未经母语者审校。",
    "ja": "> 🌐 [`{src}`]({link})（rev `{rev}`）の**日本語訳**です。英語版が正です。内容が異なる場合は英語版に従ってください。機械翻訳であり、ネイティブによる校閲は受けていません。",
    "es": "> 🌐 **Traducción al español** de [`{src}`]({link}) (rev `{rev}`). La versión en inglés es la oficial: si difieren, prevalece el inglés. Traducción automática, sin revisión de un hablante nativo.",
}
EN_ID = re.compile(r"^<!-- doc-id: (\S+) \| rev: ([0-9a-f]{8}) -->")
TR_ID = re.compile(r"^<!-- doc-id: (\S+) \| lang: (\w+) \| source-rev: ([0-9a-f]{8}) -->")
LINK = re.compile(r"(\]\()([^)\s]+)(\))")


def sources() -> list[str]:
    docs = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "docs").glob("*.md"))
    return ["README.md", *docs, "training/README.md"]


def doc_id(rel: str) -> str:
    return "readme" if rel == "README.md" else rel.removesuffix(".md").replace("/", "-").lower()


def _lines(text: str) -> list[str]:
    return text.replace("\r\n", "\n").split("\n")


def compute_rev(text: str) -> str:
    lines = _lines(text)
    if lines and (EN_ID.match(lines[0])):
        lines = lines[1:]
    return hashlib.sha256("\n".join(lines).strip().encode("utf-8")).hexdigest()[:8]


def _newline(raw: str) -> str:
    return "\r\n" if "\r\n" in raw else "\n"


def read_rev(rel: str) -> tuple[str | None, str]:
    """(rev written in the file, rev computed from its content)."""
    text = (ROOT / rel).read_text(encoding="utf-8")
    m = EN_ID.match(_lines(text)[0])
    return (m.group(2) if m else None), compute_rev(text)


def bump() -> list[str]:
    changed = []
    for rel in sources():
        path = ROOT / rel
        raw = path.read_text(encoding="utf-8")
        written, rev = read_rev(rel)
        if written == rev:
            continue
        nl = _newline(raw)
        body = nl.join(_lines(raw)[1:] if written else _lines(raw))
        path.write_text(f"<!-- doc-id: {doc_id(rel)} | rev: {rev} -->{nl}{body}", encoding="utf-8", newline="")
        changed.append(rel)
    return changed


def translation_state(lang: str, rel: str, rev: str) -> tuple[str, str]:
    """('current'|'stale'|'missing'|'invalid', source-rev found)."""
    path = LANG_DIR / lang / rel
    if not path.exists():
        return "missing", ""
    m = TR_ID.match(_lines(path.read_text(encoding="utf-8"))[0])
    if not m or m.group(1) != doc_id(rel) or m.group(2) != lang:
        return "invalid", ""
    return ("current" if m.group(3) == rev else "stale"), m.group(3)


def status_md() -> str:
    head = ["<!-- generated by scripts/docs_sync.py: do not edit -->", "# Translation status", "",
            "Generated by `python scripts/docs_sync.py bump`. English (repo root) is the source of truth; "
            "a translation is current when its `source-rev` equals the English rev.", "",
            "| Doc | Source | EN rev | " + " | ".join(f"{n} (`{c}`)" for c, n in LANGS.items()) + " |",
            "| --- | --- | --- | " + " | ".join("---" for _ in LANGS) + " |"]
    rows, totals = [], dict.fromkeys(LANGS, 0)
    for rel in sources():
        _, rev = read_rev(rel)
        cells = []
        for lang in LANGS:
            state, found = translation_state(lang, rel, rev)
            totals[lang] += state == "current"
            cells.append({"current": "✅", "missing": "❌ missing", "invalid": "⚠️ bad header",
                          "stale": f"⚠️ stale (`{found}`)"}[state])
        rows.append(f"| `{doc_id(rel)}` | [`{rel}`](../{rel}) | `{rev}` | " + " | ".join(cells) + " |")
    foot = ["", "Current: " + ", ".join(f"{c} {totals[c]}/{len(sources())}" for c in LANGS) + "."]
    return "\n".join(head + rows + foot) + "\n"


def write_status() -> None:
    LANG_DIR.mkdir(exist_ok=True)
    (LANG_DIR / "STATUS.md").write_text(status_md(), encoding="utf-8", newline="\n")


def check() -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    for rel in sources():
        written, rev = read_rev(rel)
        if written != rev:
            errors.append(f"{rel}: rev is {written}, content hash is {rev} (run: python scripts/docs_sync.py bump)")
        for lang in LANGS:
            state, found = translation_state(lang, rel, rev)
            if state == "invalid":
                errors.append(f"languages/{lang}/{rel}: missing or wrong ID line")
            elif state == "stale":
                warnings.append(f"languages/{lang}/{rel}: translated from {found}, English is {rev}")
    status = LANG_DIR / "STATUS.md"
    current = status.read_text(encoding="utf-8").replace("\r\n", "\n") if status.exists() else ""
    if current != status_md():
        errors.append("languages/STATUS.md is out of date (run: python scripts/docs_sync.py bump)")
    return errors, warnings


def _fix_links(text: str, lang: str, rel: str) -> str:
    """English-form relative links -> links valid from languages/<lang>/<rel>."""
    here = LANG_DIR / lang / rel
    src_dir, known = (ROOT / rel).parent, set(sources())
    fenced = re.compile(r"(```.*?```)", re.S)

    def fix(m: re.Match) -> str:
        target = m.group(2)
        if target.startswith(("http", "mailto:", "#")):
            return m.group(0)
        path, sep, anchor = target.partition("#")
        try:
            repo_rel = Path(os.path.normpath(src_dir / path)).relative_to(ROOT).as_posix()
        except ValueError:  # points outside the repo
            return m.group(0)
        if repo_rel in known:
            new = os.path.relpath(LANG_DIR / lang / repo_rel, here.parent)
        elif (here.parent / path).exists():
            return m.group(0)
        else:
            new = os.path.relpath(ROOT / repo_rel, here.parent)
        return f"{m.group(1)}{Path(new).as_posix()}{sep}{anchor}{m.group(3)}"

    return "".join(p if i % 2 else LINK.sub(fix, p) for i, p in enumerate(fenced.split(text)))


def stamp(lang: str, rels: list[str], rev_override: str | None = None) -> None:
    for rel in rels or sources():
        path = LANG_DIR / lang / rel
        raw = path.read_text(encoding="utf-8")
        lines = _lines(raw)
        if lines and TR_ID.match(lines[0]):
            lines = lines[1:]
        while lines and not lines[0].strip():
            lines = lines[1:]
        if lines and lines[0].startswith("> 🌐"):
            lines = lines[1:]
        while lines and not lines[0].strip():
            lines = lines[1:]
        rev = rev_override or read_rev(rel)[1]
        link = os.path.relpath(ROOT / rel, path.parent).replace("\\", "/")
        head = f"<!-- doc-id: {doc_id(rel)} | lang: {lang} | source-rev: {rev} -->\n\n"
        head += BANNERS[lang].format(src=rel, link=link, rev=rev) + "\n\n"
        body = _fix_links("\n".join(lines), lang, rel)
        if rel == "README.md":  # language bar: "English" must leave languages/<lang>/
            body = body.replace("[English](README.md)", f"[English]({link})")
        path.write_text(head + body, encoding="utf-8", newline="\n")


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "check"
    if cmd == "bump":
        print("bumped:", bump() or "nothing")
        write_status()
    elif cmd == "status":
        print(status_md())
    elif cmd == "stamp" and len(argv) >= 2 and argv[1] in LANGS:
        rev = next((a.split("=", 1)[1] for a in argv if a.startswith("--rev=")), None)
        stamp(argv[1], [a for a in argv[2:] if not a.startswith("--")], rev)
        write_status()
    elif cmd == "check":
        errors, warnings = check()
        for w in warnings:
            print("WARN ", w)
        for e in errors:
            print("ERROR", e)
        return 1 if errors else 0
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
